#:package Microsoft.CodeAnalysis.CSharp@4.14.0

using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

var fix = args.Contains("--fix");
var roots = args.Where(a => !a.StartsWith("--", StringComparison.Ordinal)).DefaultIfEmpty(".").ToArray();
var options = new CSharpParseOptions(LanguageVersion.Preview, DocumentationMode.Diagnose);
var found = 0;

foreach (var file in roots.SelectMany(r => Directory.EnumerateFiles(r, "*.cs", SearchOption.AllDirectories)).Order(StringComparer.Ordinal))
{
    var norm = file.Replace('\\', '/');
    if (norm.Contains("/obj/") || norm.Contains("/bin/") || norm.Contains("/ThirdParty/")) continue;
    var bytes = File.ReadAllBytes(file);
    var bom = bytes.Length >= 3 && bytes[0] == 0xEF && bytes[1] == 0xBB && bytes[2] == 0xBF;
    var text = Encoding.UTF8.GetString(bytes, bom ? 3 : 0, bytes.Length - (bom ? 3 : 0));
    if (text.StartsWith("// <auto-generated", StringComparison.Ordinal)) continue;

    var root = CSharpSyntaxTree.ParseText(text, options).GetRoot();
    var spans = root.DescendantTrivia(descendIntoTrivia: true)
        .Where(t => t.IsKind(SyntaxKind.SingleLineCommentTrivia) || t.IsKind(SyntaxKind.MultiLineCommentTrivia)
            || t.IsKind(SyntaxKind.SingleLineDocumentationCommentTrivia) || t.IsKind(SyntaxKind.MultiLineDocumentationCommentTrivia))
        .Where(t => !t.ToString().StartsWith("// <auto-generated", StringComparison.Ordinal))
        .Select(t => t.FullSpan)
        .ToList();
    if (spans.Count == 0) continue;

    found += spans.Count;
    if (!fix)
    {
        var lines = SourceText.From(text).Lines;
        foreach (var s in spans) Console.WriteLine($"{norm}:{lines.GetLinePosition(s.Start).Line + 1}: comment");
        continue;
    }
    File.WriteAllBytes(file, [.. (bom ? new byte[] { 0xEF, 0xBB, 0xBF } : []), .. Encoding.UTF8.GetBytes(Strip(text, spans))]);
}

if (!fix) foreach (var file in roots.SelectMany(r => Directory.EnumerateFiles(r, "*.axaml", SearchOption.AllDirectories)).Order(StringComparer.Ordinal))
{
    var norm = file.Replace('\\', '/');
    if (norm.Contains("/obj/") || norm.Contains("/bin/") || norm.Contains("/ThirdParty/")) continue;
    var lines = File.ReadAllLines(file);
    for (var i = 0; i < lines.Length; i++)
    {
        if (!lines[i].Contains("<!--", StringComparison.Ordinal)) continue;
        found++;
        Console.WriteLine($"{norm}:{i + 1}: comment");
    }
}

if (fix) Console.WriteLine($"Removed {found} comments.");
else if (found > 0)
{
    Console.Error.WriteLine($"{found} comments found. Code should explain itself; put the reason in the commit message or a test name.");
    return 1;
}
return 0;

static string Strip(string text, List<TextSpan> spans)
{
    var sb = new StringBuilder(text);
    foreach (var span in spans.OrderByDescending(s => s.Start))
    {
        var start = span.Start;
        var end = span.End;
        var lineStart = start;
        while (lineStart > 0 && text[lineStart - 1] is ' ' or '\t') lineStart--;
        var ownLine = lineStart == 0 || text[lineStart - 1] == '\n';
        var after = end;
        while (after < text.Length && text[after] is ' ' or '\t') after++;
        var lineEnds = after >= text.Length || text[after] is '\r' or '\n';
        var endedOnNewline = end > start && text[end - 1] == '\n';

        if (ownLine && (lineEnds || endedOnNewline))
        {
            start = lineStart;
            end = endedOnNewline ? end : after;
            if (!endedOnNewline && end < text.Length && text[end] == '\r') end++;
            if (!endedOnNewline && end < text.Length && text[end] == '\n') end++;
        }
        else if (lineEnds && !endedOnNewline)
        {
            start = lineStart;
            end = after;
        }
        sb.Remove(start, end - start);
    }
    return CollapseBlankLines(sb.ToString());
}

static string CollapseBlankLines(string stripped)
{
    var source = SourceText.From(stripped);
    var inString = new HashSet<int>();
    var tree = CSharpSyntaxTree.ParseText(stripped, new CSharpParseOptions(LanguageVersion.Preview));
    foreach (var node in tree.GetRoot().DescendantNodesAndTokens())
    {
        if (!(node.IsKind(SyntaxKind.StringLiteralExpression) || node.IsKind(SyntaxKind.InterpolatedStringExpression)
            || node.IsKind(SyntaxKind.Utf8StringLiteralExpression))) continue;
        var first = source.Lines.GetLinePosition(node.Span.Start).Line;
        var last = source.Lines.GetLinePosition(node.Span.End).Line;
        for (var l = first + 1; l <= last; l++) inString.Add(l);
    }

    var lines = stripped.Split('\n');
    var output = new List<string>(lines.Length);
    for (var i = 0; i < lines.Length; i++)
    {
        if (!inString.Contains(i) && lines[i].Trim().Length == 0 && i < lines.Length - 1)
        {
            var prev = output.Count > 0 ? output[^1].Trim() : null;
            var next = lines[i + 1].Trim();
            if (prev is not null && (prev.Length == 0 || prev.EndsWith('{'))) continue;
            if (next == "}" || next.StartsWith("};", StringComparison.Ordinal) || next.StartsWith("})", StringComparison.Ordinal)) continue;
        }
        output.Add(lines[i]);
    }
    return string.Join('\n', output);
}
